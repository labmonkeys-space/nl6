var ciscoAsr9902LogicalIfsAddedOIDNames = []string{}

var ciscoAsr9902LogicalIfsRemovedOIDNames = []string{}

func restoreCiscoAsr9902LogicalIfs(t *testing.T, cur map[[2]string]string) {
	t.Helper()
	reverseProfileEdits(t, cur, ciscoAsr9902Profile, "cisco_asr9902 logical interfaces", ciscoAsr9902LogicalIfsEdits)
}

func ciscoAsr9902LogicalIfsOIDNamesBefore(t *testing.T, names []string) []string {
	t.Helper()
	return reverseOIDNameEdits(t, names, "cisco_asr9902 logical interfaces", ciscoAsr9902LogicalIfsAddedOIDNames, ciscoAsr9902LogicalIfsRemovedOIDNames)
}

func TestCiscoAsr9902LogicalIfsReproduceTheParentCorpus(t *testing.T) {
	if got := corpusTagDigest(t, corpusValuesAt(t, ciscoAsr9902LogicalIfsParentRevision)); got != shippedTagDigestBeforeCiscoAsr9902LogicalIfs {
		t.Errorf("reversing the logical interfaces change gives digest %s, want %s: another shipped row changed without being recorded",
			got, shippedTagDigestBeforeCiscoAsr9902LogicalIfs)
	}
}

func TestCiscoAsr9902LogicalIfsRePinIsOnlyTheEdit(t *testing.T) {
	restored := restoreCorpusOIDNamesTo(t, collectShippedOIDs(t), ciscoAsr9902LogicalIfsParentRevision)
	if got := corpusOIDNameDigest(restored); got != shippedOIDEncodingDigestBeforeCiscoAsr9902LogicalIfs {
		t.Errorf("reversing the logical interfaces OID names gives digest %s, want %s", got, shippedOIDEncodingDigestBeforeCiscoAsr9902LogicalIfs)
	}
}
