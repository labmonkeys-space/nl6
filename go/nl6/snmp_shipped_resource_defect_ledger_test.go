// TestResourceDataDefectsReproduceTheParentCorpus is the before/after pin for
// all three transitions: reverse the ledger against today's corpus and the
// parent TAG digest must come back. A missing row, an extra row, or a
// shipped-data edit made without recording it here all fail.
//
// What it does NOT pin, measured rather than assumed: the digest hashes
// (profile, OID, first encoded byte), so a recorded oldValue is visible only
// through its tag. Two of the five nl6#569 corrections are tag-neutral
// (OCTET STRING both sides) and every one of the 829 deleted rows is restored
// only as a tag here.
// TestResourceDataDefectLedgerValuesMatchTheParentRevision closes that for all
// 834 recorded values.
func TestResourceDataDefectsReproduceTheParentCorpus(t *testing.T) {
	cur := map[[2]string]string{}
	for _, e := range shippedSNMPEntries(t) {
		k := [2]string{e.Profile, e.OID}
		if prev, dup := cur[k]; dup && prev != e.Value {
			t.Fatalf("%s serves %s twice with different values (%q, %q); the reconstruction "+
				"cannot be unambiguous", e.Profile, e.OID, prev, e.Value)
		}
		cur[k] = e.Value
	}

	// nl6#591 deleted the two writeMem entries and nl6#590 audited the Cisco arc,
	// both after nl6#576, so their reversals run first of all, newest first.
	restoreNl6590AristaArc(t, cur)
	restoreNl6591WriteMem(t, cur)
	restoreNl6590CiscoArc(t, cur)
	// nl6#576 re-homed the NVIDIA GPU arc from 1.3.6.1.4.1.53246 to 5703 after
	// this change, so today's corpus spells 225 entries differently from ec4700f.
	// Undo that first, or the digest cannot come back — the reversal is a rename,
	// so it moves keys rather than only values and nothing below would notice.
	restoreNl6576NvidiaArc(t, cur)
	restoreNl6574ResourceDefectEntries(t, cur)

	// Same line shape and hash as shippedTypedCorpus, over the distinct
	// (profile, OID, emitted tag) triples.
	seen := map[string]struct{}{}
	for k, v := range cur {
		enc := encodeTypedValue(k[1], v)
		if len(enc) == 0 {
			t.Fatalf("%s %s: encodeTypedValue(%q) emitted nothing", k[0], k[1], v)
		}
		seen[fmt.Sprintf("%s\t%s\t%02X", k[0], k[1], enc[0])] = struct{}{}
	}
	lines := make([]string, 0, len(seen))
	for l := range seen {
		lines = append(lines, l)
	}
	sort.Strings(lines)

	h := sha256.New()
	for _, l := range lines {
		h.Write([]byte(l))
		h.Write([]byte{'\n'})
	}
	got := hex.EncodeToString(h.Sum(nil))

	t.Logf("restored %d dead rows, %d bare columns and %d invalid OIDs and reverted %d value "+
		"corrections; %d (profile, OID, tag) triples reconstructed",
		len(nl6574DeletedDeadRows), len(nl6571DeletedBareColumns),
		len(nl6569DeletedInvalidOIDs), len(nl6569ValueCorrections), len(lines))

	if got != shippedTagDigestBeforeResourceDataDefects {
		t.Errorf("reconstructed parent digest = %s, want %s.\n"+
			"The ledger no longer accounts for the difference between ec4700f's shipped data "+
			"and this tree's. Either a row is missing from it, or shipped data changed without "+
			"being recorded.", got, shippedTagDigestBeforeResourceDataDefects)
	}
}

// TestResourceDataDefectLedgerIsNotVacuous guards the guard. An emptied ledger
// would make the test above pass only if the corpus were untouched, so the
// census is pinned per transition and the SHAPE of every row is checked against
// the claim made about it.
func TestResourceDataDefectLedgerIsNotVacuous(t *testing.T) {
	for _, tc := range []struct {
		name string
		got  int
		want int
	}{
		{"nl6#574 dead ifTable rows", len(nl6574DeletedDeadRows), 742},
		{"nl6#571 bare columns", len(nl6571DeletedBareColumns), 57},
		{"nl6#571 over-specified instances", len(nl6571DeletedOverSpecifiedInstances), 4},
		{"nl6#569 foreign PAN entries", len(nl6569DeletedForeignPANEntries), 24},
		{"nl6#569 invalid OIDs", len(nl6569DeletedInvalidOIDs), 2},
		{"nl6#569 value corrections", len(nl6569ValueCorrections), 5},
	} {
		if tc.got != tc.want {
			t.Errorf("%s: ledger has %d rows, want %d — the counts are the census quoted in the "+
				"commit body and the docs, so they move together or not at all",
				tc.name, tc.got, tc.want)
		}
	}

	// nl6#574: every row must be on one of the three dead columns, with exactly
	// one instance sub-identifier, and NOT on a state-seed column.
	perCol := map[int]int{}
	profiles := map[string]struct{}{}
	for _, d := range nl6574DeletedDeadRows {
		col, ok := ifTableRowColumn(d.oid)
		if !ok {
			t.Errorf("%s %s is in the dead-row ledger but is not an ifTable row OID", d.profile, d.oid)
			continue
		}
		switch col {
		case colIfLastChange, colIfInUcastPkts, colIfOutUcastPkts:
			perCol[col]++
			profiles[d.profile] = struct{}{}
		case colIfAdminStatus, colIfOperStatus:
			t.Errorf("%s %s is on a STATE-SEED column (.%d); InitIfCountersWithScenario reads it, "+
				"so it is live input and must never be deleted", d.profile, d.oid, col)
		default:
			t.Errorf("%s %s is on ifTable .%d, which nl6#574 does not cover", d.profile, d.oid, col)
		}
	}
	for col, want := range map[int]int{colIfLastChange: 646, colIfInUcastPkts: 48, colIfOutUcastPkts: 48} {
		if perCol[col] != want {
			t.Errorf("ledger holds %d ifTable .%d rows, want %d", perCol[col], col, want)
		}
	}
	if len(profiles) != 17 {
		t.Errorf("dead-row ledger spans %d profiles, want 17", len(profiles))
	}

	// THE PRECONDITION THE DELETION RESTS ON, the same one nl6#570 pinned: a
	// deleted row is replaced by the cycler only if the cycler knows that
	// ifIndex, and InitIfCounters builds its ifIndex set EXCLUSIVELY from
	// ifXTable .6 (ifHCInOctets) keys bounded by maxResourceIfIndex. So every
	// deleted (profile, ifIndex) must have an HC .6 row in the SAME profile.
	hcRows := map[string]map[string]bool{}
	for _, e := range shippedSNMPEntries(t) {
		if !strings.HasPrefix(e.OID, hcInOIDPrefix) {
			continue
		}
		idx := e.OID[len(hcInOIDPrefix):]
		if hcRows[e.Profile] == nil {
			hcRows[e.Profile] = map[string]bool{}
		}
		hcRows[e.Profile][idx] = true
	}
	orphans := 0
	for _, d := range nl6574DeletedDeadRows {
		idx := d.oid[strings.LastIndexByte(d.oid, '.')+1:]
		if !hcRows[d.profile][idx] {
			orphans++
			t.Errorf("%s %s was deleted, but the profile ships no ifXTable .6.%s row, so the "+
				"cycler knows no ifIndex %s and NOTHING answers that column now",
				d.profile, d.oid, idx, idx)
			continue
		}
		if n, err := strconv.Atoi(idx); err != nil || n < 1 || n > maxResourceIfIndex {
			orphans++
			t.Errorf("%s %s: ifIndex %q is outside 1..%d, so the cycler cannot serve it",
				d.profile, d.oid, idx, maxResourceIfIndex)
		}
	}
	if orphans == 0 {
		t.Logf("all %d deleted dead rows have an ifXTable .6 row in the same profile",
			len(nl6574DeletedDeadRows))
	}

	// And those three columns really are cycler-owned, which is the premise for
	// deleting them at all.
	owned := map[int]bool{}
	for _, c := range ifCyclerColumns {
		if c.prefix == ifTablePrefix {
			owned[c.col] = true
		}
	}
	for _, col := range []int{colIfLastChange, colIfInUcastPkts, colIfOutUcastPkts} {
		if !owned[col] {
			t.Errorf("ifTable .%d is not in ifCyclerColumns, so deleting its static entries "+
				"removed the only source of a value for it", col)
		}
	}

	// nl6#571: every deleted bare column must have been an interior node of the
	// corpus as ec4700f shipped it — reconstructed here rather than asserted,
	// because after the deletion nothing in the tree can show it.
	parent := map[string]struct{}{}
	shipped := map[[2]string]string{}
	for _, e := range shippedSNMPEntries(t) {
		parent[e.OID] = struct{}{}
		shipped[[2]string{e.Profile, e.OID}] = e.Value
	}
	for _, g := range nl6574RemovalLedgers() {
		for _, d := range g {
			parent[d.oid] = struct{}{}
		}
	}
	bareProfiles := map[string]struct{}{}
	bareOIDs := map[string]struct{}{}
	for _, d := range nl6571DeletedBareColumns {
		bareProfiles[d.profile] = struct{}{}
		bareOIDs[d.oid] = struct{}{}
		interior := false
		for o := range parent {
			if strings.HasPrefix(o, d.oid+".") {
				interior = true
				break
			}
		}
		if !interior {
			t.Errorf("%s %s is in the bare-column ledger, but at ec4700f no shipped OID extended "+
				"it, so it was not an interior node and this ledger misclassifies it",
				d.profile, d.oid)
		}
	}
	if len(bareOIDs) != 14 || len(bareProfiles) != 13 {
		t.Errorf("bare-column ledger spans %d distinct OIDs across %d profiles, want 14 and 13",
			len(bareOIDs), len(bareProfiles))
	}

	// nl6#571, the over-specified four. The claim is the INVERSE of the bare
	// column: the row is not an interior node, its PROPER PREFIX is a legal
	// instance that shipped at ec4700f and still ships today. That is what makes
	// the first cut's mistake visible in the ledger rather than only in prose —
	// it deleted the prefix and kept this row.
	for _, d := range nl6571DeletedOverSpecifiedInstances {
		cut := strings.LastIndexByte(d.oid, '.')
		if cut <= 0 {
			t.Errorf("%s %s has no proper prefix", d.profile, d.oid)
			continue
		}
		prefix := d.oid[:cut]
		if _, ok := parent[prefix]; !ok {
			t.Errorf("%s %s is in the over-specified ledger, but %s did not ship at ec4700f, so "+
				"this row was not the extending sibling of a legal instance",
				d.profile, d.oid, prefix)
		}
		if got := shipped[[2]string{d.profile, prefix}]; got == "" {
			t.Errorf("%s no longer serves %s. The over-specified row was deleted INSTEAD of its "+
				"legal prefix; if the prefix is gone too, the inversion has been reintroduced",
				d.profile, prefix)
		}
	}

	// nl6#569, the foreign PAN entries: a non-Palo-Alto profile serving a Palo
	// Alto enterprise OID. Both halves of that are the claim.
	foreignProfiles := map[string]struct{}{}
	for _, d := range nl6569DeletedForeignPANEntries {
		if !strings.HasPrefix(d.oid, panEnterprisePrefix) {
			t.Errorf("%s %s is in the foreign-PAN ledger but is not under %s",
				d.profile, d.oid, panEnterprisePrefix)
		}
		if d.profile == paloAltoProfile {
			t.Errorf("%s %s is in the FOREIGN PAN ledger but palo_alto_pa3220 is the Palo Alto "+
				"profile; its own PAN OIDs are corrections, not deletions", d.profile, d.oid)
		}
		foreignProfiles[d.profile] = struct{}{}
	}
	if len(foreignProfiles) != 12 {
		t.Errorf("foreign-PAN ledger spans %d profiles, want 12", len(foreignProfiles))
	}

	// nl6#569: the tags are the wire claim, so both sides are asserted against
	// the encoder rather than trusted from the table.
	tagMoves := 0
	for _, c := range nl6569ValueCorrections {
		if enc := encodeTypedValue(c.oid, c.oldValue); len(enc) == 0 || enc[0] != c.oldTag {
			t.Errorf("%s %s: old value %q encodes as % x, ledger says tag 0x%02X",
				c.profile, c.oid, c.oldValue, enc, c.oldTag)
		}
		if enc := encodeTypedValue(c.oid, c.newValue); len(enc) == 0 || enc[0] != c.newTag {
			t.Errorf("%s %s: new value %q encodes as % x, ledger says tag 0x%02X",
				c.profile, c.oid, c.newValue, enc, c.newTag)
		}
		// Every correction lands on a DisplayString object, so the corrected
		// value must go out as an OCTET STRING. That is the defect: a real
		// vendor OID answering a number where a string belongs.
		if c.newTag != ASN1_OCTET_STRING {
			t.Errorf("%s %s: corrected value %q emits tag 0x%02X, but every nl6#569 correction "+
				"targets a DisplayString", c.profile, c.oid, c.newValue, c.newTag)
		}
		if c.oldTag != c.newTag {
			tagMoves++
		}
	}
	if tagMoves != 3 {
		t.Errorf("%d of the nl6#569 corrections move the emitted tag, want 3", tagMoves)
	}
}

// nl6574ValueDigestAtEc4700f is a SHA-256 over the sorted
// "profile\tOID\tvalue" lines of every row this ledger records, as it existed at
// ec4700f, the revision this branch forked from.
//
// It was computed by reading the resource files OUT OF GIT at that revision
// (`git show ec4700f:<path>`), not from the ledger table, so comparing the table
// against it is a comparison with the tree as it actually was. A digest derived
// from the table would only prove the table equals itself.
const nl6574ValueDigestAtEc4700f = "2460878e6276626b72558e97413aa17bc52635dca38258faa8cb7bd0ba9f3fd6"

// TestResourceDataDefectLedgerValuesMatchTheParentRevision pins the ledger's
// VALUES, which the tag digest cannot see. Without it the recorded oldValues are
// unfalsifiable for the 829 deleted rows: the deletion removed them from the
// tree, so nothing else in the package has anything left to compare against.
//
// If it fails after an edit to the tables, the tables are wrong — the parent
// revision cannot change.
func TestResourceDataDefectLedgerValuesMatchTheParentRevision(t *testing.T) {
	lines := []string{}
	for _, g := range nl6574RemovalLedgers() {
		for _, d := range g {
			lines = append(lines, fmt.Sprintf("%s\t%s\t%s", d.profile, d.oid, d.oldValue))
		}
	}
	for _, c := range nl6569ValueCorrections {
		lines = append(lines, fmt.Sprintf("%s\t%s\t%s", c.profile, c.oid, c.oldValue))
	}
	sort.Strings(lines)

	h := sha256.New()
	for _, l := range lines {
		h.Write([]byte(l))
		h.Write([]byte{'\n'})
	}
	got := hex.EncodeToString(h.Sum(nil))

	if got != nl6574ValueDigestAtEc4700f {
		t.Errorf("ledger value digest = %s, want %s (%d rows).\n"+
			"The recorded (profile, OID, value) triples no longer match what ec4700f shipped. "+
			"Re-derive with: git show ec4700f:<part> for every part under go/nl6/resources, "+
			"collect the rows this ledger names, and hash sorted \"profile\\tOID\\tvalue\" "+
			"lines. Do not re-pin this constant to match an edited table: the parent revision "+
			"is fixed.", got, nl6574ValueDigestAtEc4700f, len(lines))
	}
	t.Logf("all %d recorded values match the corpus at ec4700f", len(lines))
}

// nl6574DeletedOIDNames returns the DISTINCT OID names this change removed from
// the corpus, in the undotted spelling collectShippedOIDs uses. Derived from the
// ledger rather than tabled a second time, so the two views cannot drift.
func nl6574DeletedOIDNames() []string {
	seen := map[string]struct{}{}
	var out []string
	for _, g := range nl6574RemovalLedgers() {
		for _, d := range g {
			o := strings.TrimPrefix(d.oid, ".")
			if _, dup := seen[o]; dup {
				continue
			}
			seen[o] = struct{}{}
			out = append(out, o)
		}
	}
	sort.Strings(out)
	return out
}

// TestResourceDataDefectRePinIsOnlyTheDeletedOIDs makes this change's re-pin of
// shippedOIDEncodingDigest self-proving instead of a claim in a comment: put the
// deleted OID names back and the pre-change digest must return exactly. It can
// only return if every surviving shipped OID still encodes to the same bytes,
// which is the compatibility claim the re-pin rests on.
//
// The five nl6#569 value corrections do not appear here at all, which is the
// point of doing it this way: they change values, not OID names, so the OID
// digest must be explained by the deleted names alone.
// nl6574RestorableOIDNames is nl6574DeletedOIDNames minus the names that are
// STILL in the corpus, which is what an OID-digest reversal must add back: that
// digest hashes DISTINCT names corpus-wide, so a name another profile still
// serves never left and restoring it would double-count.
//
// Exactly one name is in that position and it is pinned here rather than
// filtered silently: panChassisType was deleted from twelve foreign profiles
// (nl6#569's corpus-wide half) while palo_alto_pa3220 still serves it, corrected
// to "PA-3220". A future edit that removed the last copy, or that left a
// deletion incomplete, changes this partition and fails here — which is the
// point of asserting it instead of computing it.
//
// Shared by all three reversal sites (this change's, nl6#570's and nl6#541's)
// so the partition cannot be got right in one and wrong in another.
func nl6574RestorableOIDNames(t *testing.T) []string {
	t.Helper()

	shipped := map[string]struct{}{}
	for _, o := range collectShippedOIDs(t) {
		shipped[o] = struct{}{}
	}
	var toRestore, stillShipped []string
	for _, o := range nl6574DeletedOIDNames() {
		if _, ok := shipped[o]; ok {
			stillShipped = append(stillShipped, o)
			continue
		}
		toRestore = append(toRestore, o)
	}
	if len(stillShipped) != 1 || stillShipped[0] != "1.3.6.1.4.1.25461.2.1.2.2.1.0" {
		t.Fatalf("deleted names still shipped = %v, want exactly "+
			"[1.3.6.1.4.1.25461.2.1.2.2.1.0] (panChassisType, kept by the Palo Alto profile). "+
			"Either a deletion is incomplete, or the last copy of a name has gone and the OID "+
			"digest needs re-deriving", stillShipped)
	}
	if len(toRestore) != 258 {
		t.Errorf("%d deleted names vanished from the corpus, want 258", len(toRestore))
	}
	return toRestore
}

