// TestNoShippedWalkEmitsABareColumnOID is the nl6#571 SYMPTOM test, and it is
// the one no existing test could see: TestBareColumnCensusHasNotGrown reads the
// JSON, so it says what the corpus CONTAINS, not what a walk EMITS. Those differ
// — the cycler serves columns no profile ships rows for, and it also shadows
// columns whose static rows nl6#570 and nl6#574 deleted — so the property that
// actually matters has to be measured on the serve path.
//
// It walks every shipped profile through findNextOIDWithServed, the function the
// GETNEXT / GETBULK loop itself calls, and collects every OID a binding would be
// named with. An emitted OID is a BARE COLUMN if some OID emitted by the walk of
// ANY shipped profile extends it: that is the defect, because the walk hands a
// manager a varbind whose name is a column rather than an instance.
//
// The union is load-bearing, and getting it wrong is how this test passed while
// proving nothing. Judged against one profile's OWN output, the four surviving
// bare hrStorageAllocationUnits entries are invisible: those profiles ship no
// instantiated hrStorageTable row at all, so nothing in their own walk extends
// the column and it looks like an ordinary leaf. It is the walks of
// dell_poweredge_r750, hpe_proliant_dl380 and the NVIDIA profiles that show
// .25.2.3.1.4 to be a column. Legality is a property of the OID, not of which
// profile carries it — the same correction TestBareColumnCensusHasNotGrown needed.
//
// There is no carve-out and no allowance: the count must be ZERO. nl6#571's
// Block If — the four bare hrStorageAllocationUnits entries whose profiles ship
// no other hrStorageTable row — was decided as DELETE, because a collector
// getting nothing is honest about a device type that models no storage, while a
// collector getting one binding named with a column OID is being handed an
// illegal varbind name. Those four profiles now model no storage, and that is
// the correct outcome: do not restore the row to make the table non-empty.
//
// A test that requires zero of something cannot fail on its own, so this one
// starts with assertBareColumnDetectionIsCorpusWide — the control shared with
// TestBareColumnCensusHasNotGrown, which plants a bare column in one profile and
// its instance in ANOTHER and requires the detector to report it. Narrow the scan
// back to a single profile and that control fails here and in the census. It
// replaces a control that could not do this: the previous one planted the column
// and its instance in the same set, which a per-profile scan still finds, so
// both guards could be narrowed with the whole suite green (nl6#571 review B1).
//
// It also asserts a floor on the OIDs walked, so a walk that stopped early cannot
// pass by having nothing to find a column in.
func TestNoShippedWalkEmitsABareColumnOID(t *testing.T) {
	assertBareColumnDetectionIsCorpusWide(t)

	// A generous per-profile bound: the widest shipped profile walks a few tens
	// of thousands of OIDs, and a runaway walk is a defect in its own right.
	const maxSteps = 200000
	// A floor on the total. Measured at 42127 today; the floor is deliberately
	// slack, because its job is to catch a walk that broke, not to pin a count.
	const walkedFloor = 40000

	profiles := shippedProfileNames(t)
	emitted := map[string]map[string]struct{}{} // profile -> emitted OIDs
	totalSteps := 0

	for _, profile := range profiles {
		srv := deviceForProfile(t, profile)
		served := srv.lldpServedOIDs()

		set := map[string]struct{}{}
		cur := ""
		for len(set) < maxSteps {
			next, _ := srv.findNextOIDWithServed(cur, served)
			if next == "" || (cur != "" && compareOIDs(next, cur) <= 0) {
				break
			}
			set[normaliseResourceOID(next)] = struct{}{}
			cur = next
		}
		if len(set) == 0 {
			t.Errorf("%s: the walk emitted nothing, so this profile proves nothing", profile)
			continue
		}
		if len(set) >= maxSteps {
			t.Errorf("%s: the walk did not terminate within %d steps", profile, maxSteps)
		}
		totalSteps += len(set)
		emitted[profile] = set
	}
	if totalSteps < walkedFloor {
		t.Errorf("the walks emitted %d OIDs in total, want at least %d: too few to conclude "+
			"anything about what a walk names", totalSteps, walkedFloor)
	}

	found := bareColumnsAcrossProfiles(emitted)
	for k, ext := range found {
		t.Errorf("%s: a walk emits a binding named %s, which %s extends — so it is a table column "+
			"with no instance sub-identifier, which is not a legal varbind name. Check the table's "+
			"INDEX arity before deleting: at ciscoImageString the EXTENDING name was the illegal "+
			"one, and nl6#571's first cut deleted the legal instance because of it", k[0], k[1], ext)
	}
	if msg := bareColumnCountViolation(len(found), 0); msg != "" {
		t.Error(msg)
	}
	if !t.Failed() {
		t.Logf("%d OIDs walked across %d profiles; none of them is a column node",
			totalSteps, len(profiles))
	}
}

// TestEveryDeletedDeadRowIsAnsweredByTheCycler fires on the DEFECT rather than
// on a digest, which is the lesson nl6#570 recorded: the corpus digests' own
// documented remedy is to re-pin, so a later profile edit that left one of these
// columns answered by NOTHING would be reported as "update the golden value".
//
// The ledger's HC .6 precondition says the cycler KNOWS the ifIndex. This says
// the value comes out, through findResponse, on a device built the way both
// production creation paths build one. Both are needed: the precondition is what
// explains a failure, this is what detects one.
func TestEveryDeletedDeadRowIsAnsweredByTheCycler(t *testing.T) {
	byProfile := map[string][]string{}
	for _, d := range nl6574DeletedDeadRows {
		byProfile[d.profile] = append(byProfile[d.profile], d.oid)
	}

	answered := 0
	for profile, oids := range byProfile {
		srv := deviceForProfile(t, profile)
		for _, oid := range oids {
			got := srv.findResponse(oid)
			switch {
			case got == "":
				t.Errorf("%s: %s was deleted as dead data, but nothing answers it now. The cycler "+
					"was supposed to be serving that column already — do NOT re-add the static "+
					"row and do NOT re-pin a corpus digest; find out why the cycler is silent",
					profile, oid)
			case isSNMPExceptionValue(got):
				t.Errorf("%s: %s answers the exception %q", profile, oid, got)
			default:
				answered++
			}
		}
	}
	if answered != len(nl6574DeletedDeadRows) {
		t.Errorf("%d of %d deleted dead rows are answered dynamically", answered, len(nl6574DeletedDeadRows))
	}
	t.Logf("all %d deleted rows are answered by the cycler across %d profiles",
		answered, len(byProfile))
}

// TestPaloAltoPANSubtreeMatchesTheMIB is the nl6#569 audit, committed as a test
// rather than left in an issue. It is the ONLY form of check available here: no
// load guard can see this defect, because every wrong value was a
// DisplayString-compatible string on an OID oidTypeTable does not type, so all
// three encodability rules passed the whole table (nl6#523, nl6#529, nl6#541).
//
// What it asserts is what a test CAN assert — the exact value served and the tag
// it goes out as, plus the absence of the three OIDs that cannot exist. It does
// not and cannot assert that the value is faithful to the MIB; that came from
// reading PAN-COMMON-MIB, and this table is the record of that reading. Read it
// as "these are the values nl6#569 resolved", never as "these are verified
// against a MIB by CI".
func TestPaloAltoPANSubtreeMatchesTheMIB(t *testing.T) {
	const panPrefix = panEnterprisePrefix + ".2.1.2."

	// panMgmtPanorama2Connected reads "not-connected": a PA-3220 with one
	// Panorama is the ordinary case, and answering "connected" on both would
	// assert a second Panorama that nothing else in the profile models.

	srv := deviceForProfile(t, paloAltoProfile)

	// The 8 OIDs that survive, with the object each one is. Every one is a
	// DisplayString except panSessionActive, which is an Integer32.
	for _, tc := range []struct {
		oid, object, want string
		tag               byte
	}{
		{panPrefix + "1.1.0", "panSysSwVersion", "10.1.6-h2", ASN1_OCTET_STRING},
		{panPrefix + "1.3.0", "panSysSerialNumber", "PA3220-SN001234", ASN1_OCTET_STRING},
		{panPrefix + "1.6.0", "panSysVpnClientVersion", "5.2.10", ASN1_OCTET_STRING},
		{panPrefix + "1.17.0", "panSysWildfireVersion", "790286-4437636", ASN1_OCTET_STRING},
		{panPrefix + "2.1.0", "panChassisType", "PA-3220", ASN1_OCTET_STRING},
		{panPrefix + "3.3.0", "panSessionActive", "1800", ASN1_INTEGER},
		{panPrefix + "4.1.0", "panMgmtPanoramaConnected", "connected", ASN1_OCTET_STRING},
		{panPrefix + "4.2.0", "panMgmtPanorama2Connected", "not-connected", ASN1_OCTET_STRING},
	} {
		got := srv.findResponse(tc.oid)
		if got != tc.want {
			t.Errorf("%s (%s) answers %q, want %q", tc.oid, tc.object, got, tc.want)
			continue
		}
		if enc := encodeTypedValue(tc.oid, got); len(enc) == 0 || enc[0] != tc.tag {
			t.Errorf("%s (%s) = %q emits % x, want tag 0x%02X", tc.oid, tc.object, got, enc, tc.tag)
		}
	}

	// The three that cannot exist. .4.1.3 and .4.1.3.1 sit UNDERNEATH a leaf
	// scalar (panMgmtPanoramaConnected), where nothing can be defined; .5.1.0
	// instantiates panGPGatewayUtilization, an OBJECT-IDENTITY container with
	// three children and therefore no instance of its own.
	for _, tc := range []struct{ oid, why string }{
		{panPrefix + "4.1.3", "under the leaf scalar panMgmtPanoramaConnected"},
		{panPrefix + "4.1.3.1", "under the leaf scalar panMgmtPanoramaConnected"},
		{panPrefix + "5.1.0", "panGPGatewayUtilization is an OBJECT-IDENTITY container, not a leaf"},
	} {
		if got := srv.findResponse(tc.oid); got != "" && !isSNMPExceptionValue(got) {
			t.Errorf("%s still answers %q; it is not a valid OID (%s)", tc.oid, got, tc.why)
		}
	}

	// panMgmt holds exactly two scalars, so nothing else may appear under .4,
	// and .5 must stay empty until the three real panGPGWUtilization* children
	// are added with their own sub-identifiers (deliberately NOT invented here).
	for _, e := range shippedSNMPEntries(t) {
		if e.Profile != paloAltoProfile || !strings.HasPrefix(e.OID, panPrefix+"4.") {
			continue
		}
		if e.OID != panPrefix+"4.1.0" && e.OID != panPrefix+"4.2.0" {
			t.Errorf("%s serves %s, but panMgmt contains only panMgmtPanoramaConnected (.4.1) "+
				"and panMgmtPanorama2Connected (.4.2)", e.Part, e.OID)
		}
	}
}

// TestNoForeignPANOIDsShip is the corpus-wide half of nl6#569, and it exists
// because TestPaloAltoPANSubtreeMatchesTheMIB cannot see the defect: that test
// builds one device from one profile, so twelve OTHER profiles serving Palo Alto
// enterprise OIDs were invisible to it, and to every load guard, and to both
// corpus digests (the values encode fine — they are simply not this device's
// objects).
//
// A vendor enterprise subtree is an identity claim. An Arista answering
// panChassisType is not a fidelity approximation, it is a different vendor's MIB
// on the wire, and a collector keyed on PAN-COMMON-MIB would treat that device as
// a firewall. nl6#569 deleted 24 such entries across 12 profiles; the wider
// cross-vendor audit is nl6#576, and this test is the part of it this change can
// honestly close.
func TestNoForeignPANOIDsShip(t *testing.T) {
	// Positive control: the check must be able to see a planted entry, or the
	// zero below would be vacuous in the same way nl6#571's census was.
	if !isForeignPANEntry("arista_7280r3.json", panEnterprisePrefix+".2.1.2.2.1.0") {
		t.Fatal("isForeignPANEntry does not flag a PAN OID on a non-PAN profile; the assertion " +
			"below cannot fail")
	}
	if isForeignPANEntry(paloAltoProfile, panEnterprisePrefix+".2.1.2.2.1.0") {
		t.Fatal("isForeignPANEntry flags the Palo Alto profile's own PAN OIDs")
	}

	offenders := map[string][]string{}
	panOwn := 0
	for _, e := range shippedSNMPEntries(t) {
		switch {
		case isForeignPANEntry(e.Profile, e.OID):
			offenders[e.Profile] = append(offenders[e.Profile], e.OID)
		case strings.HasPrefix(e.OID, panEnterprisePrefix+"."):
			panOwn++
		}
	}
	for profile, oids := range offenders {
		sort.Strings(oids)
		t.Errorf("%s serves %d OID(s) under the Palo Alto enterprise arc %s: %v. Delete them — "+
			"do not correct them; a non-Palo-Alto device should not answer a PAN OID at all",
			profile, len(oids), panEnterprisePrefix, oids)
	}

	// And the Palo Alto profile must still serve its own, or the check above
	// would also pass on a corpus that had lost the subtree entirely.
	if panOwn == 0 {
		t.Errorf("no profile serves anything under %s any more, so this test would pass on an "+
			"empty corpus", panEnterprisePrefix)
	}
	t.Logf("%d PAN entries ship, all on %s; %d foreign", panOwn, paloAltoProfile, len(offenders))
}

// isForeignPANEntry is the rule, as a function so the control can exercise it.
func isForeignPANEntry(profile, oid string) bool {
	return strings.HasPrefix(oid, panEnterprisePrefix+".") && profile != paloAltoProfile
}
