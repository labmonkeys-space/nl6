// and ifStackTable rows (machine-generated by diffing the generated chassis
// part at the parent revision against this change), the ipAddrTable rows for
// both addresses, the connected ipRouteTable row for 10.0.0.0 via ifIndex 78,
// and nothing else. The lo0.0 /32 is a host route, mirrored on no profile.
// The OID names below that no other profile serves are new to the corpus; no
// value changed its tag.

