var mx10004SystemInterfacesRemovedOIDNames = []string{}

func restoreMx10004SystemInterfaces(t *testing.T, cur map[[2]string]string) {
	t.Helper()
	reverseProfileEdits(t, cur, juniperMx10004Profile, "juniper_mx10004 system interfaces", mx10004SystemInterfacesEdits)
}

func mx10004SystemInterfacesOIDNamesBefore(t *testing.T, names []string) []string {
	t.Helper()
	return reverseOIDNameEdits(t, names, "juniper_mx10004 system interfaces", mx10004SystemInterfacesAddedOIDNames, mx10004SystemInterfacesRemovedOIDNames)
}

func TestMx10004SystemInterfacesReproduceTheParentCorpus(t *testing.T) {
	if got := corpusTagDigestAt(t, corpusValuesAt(t, mx10004SystemInterfacesParentRevision), mx10004SystemInterfacesParentRevision); got != shippedTagDigestBeforeMx10004SystemInterfaces {
		t.Errorf("reversing the system interfaces change gives digest %s, want %s: another shipped row changed without being recorded",
			got, shippedTagDigestBeforeMx10004SystemInterfaces)
	}
}

func TestMx10004SystemInterfacesRePinIsOnlyTheEdit(t *testing.T) {
	restored := restoreCorpusOIDNamesTo(t, collectShippedOIDs(t), mx10004SystemInterfacesParentRevision)
	if got := corpusOIDNameDigest(restored); got != shippedOIDEncodingDigestBeforeMx10004SystemInterfaces {
		t.Errorf("reversing the system interfaces OID names gives digest %s, want %s", got, shippedOIDEncodingDigestBeforeMx10004SystemInterfaces)
	}
}
