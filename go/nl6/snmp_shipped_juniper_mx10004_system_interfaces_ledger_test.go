// ipAddrTable served 192.168.1.1 only, because the chassis model knew no
// interface the Routing Engine owns. The model gained fxp0 (ethernetCsmacd,
// 1 Gbit/s, MTU 1514) and lo0 (softwareLoopback, no MAC, speed 0), numbered
