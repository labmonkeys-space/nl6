func TestRouteTableReproducesTheParentCorpus(t *testing.T) {
	if got := corpusTagDigestAt(t, corpusValuesAt(t, routeTableParentRevision), routeTableParentRevision); got != shippedTagDigestBeforeRouteTable {
		t.Errorf("reversing the route table change gives digest %s, want %s: another shipped row changed without being recorded",
			got, shippedTagDigestBeforeRouteTable)
	}
}

