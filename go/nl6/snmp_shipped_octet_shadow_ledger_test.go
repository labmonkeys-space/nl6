const shippedTagDigestBeforeOctetShadowDeletion = "e29712b12dacffa0106f615ad637d6145140ee8b54eb23a0fe3745291fa62237"

// restoreNl6570OctetEntries adds the deleted rows back to a (profile, OID) ->
// value map, failing if any of them still ships. Shared with
// TestShippedDataEditsReproduceTheParentCorpus, whose own reversal starts from
// the tree this ledger reconstructs.
func restoreNl6570OctetEntries(t *testing.T, cur map[[2]string]string) {
	t.Helper()
	for _, d := range nl6570DeletedOctetEntries {
		k := [2]string{d.profile, d.oid}
		if got, ok := cur[k]; ok {
			t.Errorf("%s %s is in the nl6#570 removal ledger but still ships, valued %q. The "+
				"cycler now serves that column, so a static entry is unreachable dead data",
				d.profile, d.oid, got)
			continue
		}
		cur[k] = d.oldValue
	}
}

// TestOctetShadowDeletionReproducesTheParentCorpus is the before/after pin for
// the data half of nl6#570. Reversing the ledger against today's corpus must
// reproduce the parent TAG digest, so a missing row, an extra row, or a
// shipped-data edit made without recording it here all fail.
//
// WHAT IT DOES NOT PIN, measured rather than assumed (review B3): the digest
// hashes (profile, OID, first encoded byte), so a recorded oldValue is visible
// only through its TAG. Changing 1012345678 to 1012345679 leaves this test —
// and the whole package — passing, because both encode as Counter32. Only the
// 30 rows shared with nl6541TagChanges have their values pinned here, and that
// is incidental. TestOctetShadowLedgerValuesMatchTheParentRevision closes it
// for all 1322.
func TestOctetShadowDeletionReproducesTheParentCorpus(t *testing.T) {
	cur := map[[2]string]string{}
	for _, e := range shippedSNMPEntries(t) {
		k := [2]string{e.Profile, e.OID}
		if prev, dup := cur[k]; dup && prev != e.Value {
			t.Fatalf("%s serves %s twice with different values (%q, %q); the reconstruction "+
				"cannot be unambiguous", e.Profile, e.OID, prev, e.Value)
		}
		cur[k] = e.Value
	}

	// nl6#590, nl6#576 and then nl6#574 / nl6#571 / nl6#569 edited shipped data
	// AFTER this change, so the reversal chains: undo those transitions
	// newest-first, which reconstructs the tree nl6#570 left, and only then put
	// this change's octet rows back.
	restoreNl6590CiscoArc(t, cur)
	restoreNl6576NvidiaArc(t, cur)
	restoreNl6574ResourceDefectEntries(t, cur)
	restoreNl6570OctetEntries(t, cur)

	// Same line shape and hash as shippedTypedCorpus, over the distinct
	// (profile, OID, emitted tag) triples.
	seen := map[string]struct{}{}
	for k, v := range cur {
		enc := encodeTypedValue(k[1], v)
		if len(enc) == 0 {
			t.Fatalf("%s %s: encodeTypedValue(%q) emitted nothing", k[0], k[1], v)
		}
		seen[fmt.Sprintf("%s\t%s\t%02X", k[0], k[1], enc[0])] = struct{}{}
	}
	lines := make([]string, 0, len(seen))
	for l := range seen {
		lines = append(lines, l)
	}
	sort.Strings(lines)

	h := sha256.New()
	for _, l := range lines {
		h.Write([]byte(l))
		h.Write([]byte{'\n'})
	}
	got := hex.EncodeToString(h.Sum(nil))

	t.Logf("restored %d deleted rows; %d (profile, OID, tag) triples reconstructed",
		len(nl6570DeletedOctetEntries), len(lines))

	if got != shippedTagDigestBeforeOctetShadowDeletion {
		t.Errorf("reconstructed parent digest = %s, want %s.\n"+
			"The ledger no longer accounts for the difference between 3a69927's shipped data "+
			"and this tree's. Either a row is missing from it, or shipped data changed without "+
			"being recorded.", got, shippedTagDigestBeforeOctetShadowDeletion)
	}
}

// TestOctetShadowLedgerIsNotVacuous guards the guard. An emptied ledger, or a
// reconstruction that silently skipped it, would make the test above pass only
// if the corpus were untouched — so the census is pinned to what the mechanical
// recount reported, per column, and the OID shape of every row is checked.
//
// The census matters on its own: issue #570 says 661, which is one column. The
// figure is 1322.
func TestOctetShadowLedgerIsNotVacuous(t *testing.T) {
	const (
		wantTotal    = 1322
		wantPerCol   = 661
		wantProfiles = 20
	)
	if len(nl6570DeletedOctetEntries) != wantTotal {
		t.Errorf("ledger has %d rows, want %d — the census is the number quoted in the commit "+
			"body and the docs, so they move together or not at all",
			len(nl6570DeletedOctetEntries), wantTotal)
	}

	perCol := map[string]int{}
	profiles := map[string]struct{}{}
	for _, d := range nl6570DeletedOctetEntries {
		profiles[d.profile] = struct{}{}
		switch {
		case strings.HasPrefix(d.oid, ifTablePrefix+"10."):
			perCol["10"]++
		case strings.HasPrefix(d.oid, ifTablePrefix+"16."):
			perCol["16"]++
		default:
			t.Errorf("%s %s is in the octet-shadow ledger but is neither ifInOctets (.10) nor "+
				"ifOutOctets (.16)", d.profile, d.oid)
			continue
		}
		// Every deleted row was a Counter32 on the wire, which is what makes the
		// dynamic replacement tag-neutral. Asserted against the encoder, not the
		// type table, because the wire is the claim.
		if enc := encodeTypedValue(d.oid, d.oldValue); len(enc) == 0 || enc[0] != ASN1_COUNTER32 {
			t.Errorf("%s %s: old value %q encodes as % x, want a Counter32 (0x%02X)",
				d.profile, d.oid, d.oldValue, enc, ASN1_COUNTER32)
		}
	}
	if perCol["10"] != wantPerCol || perCol["16"] != wantPerCol {
		t.Errorf("ledger holds %d .10 rows and %d .16 rows, want %d each: #570's 661 was ONE "+
			"column, and a ledger covering only one column would leave the other's static "+
			"entries shipping as dead data", perCol["10"], perCol["16"], wantPerCol)
	}
	if len(profiles) != wantProfiles {
		t.Errorf("ledger spans %d profiles, want %d", len(profiles), wantProfiles)
	}

	// THE PRECONDITION THE WHOLE DELETION RESTS ON (review R6). A deleted row is
	// replaced by the cycler only if the cycler knows that ifIndex, and
	// InitIfCounters builds its ifIndex set EXCLUSIVELY from ifXTable .6
	// (ifHCInOctets) keys, bounded by maxResourceIfIndex. So every deleted
	// (profile, ifIndex) must have an HC .6 row in the SAME profile. It holds
	// today across all 20 profiles with zero orphans; nothing pinned it, and a
	// later profile edit that drops or renumbers HC .6 rows would leave those
	// columns answering NOTHING — a silent hole where a frozen value used to be.
	hcRows := map[string]map[string]bool{}
	for _, e := range shippedSNMPEntries(t) {
		if !strings.HasPrefix(e.OID, hcInOIDPrefix) {
			continue
		}
		idx := e.OID[len(hcInOIDPrefix):]
		if hcRows[e.Profile] == nil {
			hcRows[e.Profile] = map[string]bool{}
		}
		hcRows[e.Profile][idx] = true
	}
	orphans := 0
	for _, d := range nl6570DeletedOctetEntries {
		idx := d.oid[strings.LastIndexByte(d.oid, '.')+1:]
		if !hcRows[d.profile][idx] {
			orphans++
			t.Errorf("%s %s was deleted, but the profile ships no ifXTable .6.%s row, so the "+
				"cycler knows no ifIndex %s and NOTHING answers that column now", d.profile, d.oid, idx, idx)
			continue
		}
		if n, err := strconv.Atoi(idx); err != nil || n < 1 || n > maxResourceIfIndex {
			orphans++
			t.Errorf("%s %s: ifIndex %q is outside 1..%d, so the cycler cannot serve it",
				d.profile, d.oid, idx, maxResourceIfIndex)
		}
	}
	if orphans == 0 {
		t.Logf("all %d deleted rows have an ifXTable .6 row in the same profile, so every one is "+
			"replaced by the cycler", len(nl6570DeletedOctetEntries))
	}

	// And the columns really are cycler-owned now, which is the premise for
	// deleting them at all.
	owned := map[int]bool{}
	for _, c := range ifCyclerColumns {
		if c.prefix == ifTablePrefix {
			owned[c.col] = true
		}
	}
	for _, col := range []int{colIfInOctets, colIfOutOctets} {
		if !owned[col] {
			t.Errorf("ifTable .%d is not in ifCyclerColumns, so deleting its static entries "+
				"removed the only source of a value for it", col)
		}
	}
}

// nl6570OctetValueDigestAt3a69927 is a SHA-256 over the sorted
// "profile\tOID\tvalue" lines of every ifTable .10 / .16 row as it existed at
// 3a69927, the revision this branch forked from.
//
// It was computed by reading the resource files OUT OF GIT at that revision
// (`git show 3a69927:<path>`), not from the ledger table, so comparing the table
// against it is a comparison with the tree as it actually was. A digest derived
// from the table would only prove the table equals itself.
const nl6570OctetValueDigestAt3a69927 = "a21077a8e5ceb0c38196cb424ce6b462ebc4233279da9253064a7a05e62f1261"

// TestOctetShadowLedgerValuesMatchTheParentRevision pins the ledger's VALUES,
// which the tag digest cannot see (review B3). Without it the ledger's recorded
// oldValues are unfalsifiable for 1292 of 1322 rows: the deletion removed them
// from the tree, so nothing else in the package has anything left to compare
// them against.
//
// This is what makes the ledger a record rather than an assertion. If it fails
// after an edit to the table, the table is wrong — the parent revision cannot
// change.
func TestOctetShadowLedgerValuesMatchTheParentRevision(t *testing.T) {
	lines := make([]string, 0, len(nl6570DeletedOctetEntries))
	for _, d := range nl6570DeletedOctetEntries {
		lines = append(lines, fmt.Sprintf("%s\t%s\t%s", d.profile, d.oid, d.oldValue))
	}
	sort.Strings(lines)

	h := sha256.New()
	for _, l := range lines {
		h.Write([]byte(l))
		h.Write([]byte{'\n'})
	}
	got := hex.EncodeToString(h.Sum(nil))

	if got != nl6570OctetValueDigestAt3a69927 {
		t.Errorf("ledger value digest = %s, want %s (%d rows).\n"+
			"The recorded (profile, OID, value) triples no longer match what 3a69927 shipped. "+
			"Re-derive with: git show 3a69927:<part> for every part under go/nl6/resources, "+
			"collect the .2.2.1.10 / .2.2.1.16 entries, and hash sorted "+
			"\"profile\\tOID\\tvalue\" lines. Do not re-pin this constant to match an edited "+
			"table: the parent revision is fixed.", got, nl6570OctetValueDigestAt3a69927, len(lines))
	}
	t.Logf("all %d recorded values match the corpus at 3a69927", len(lines))
}

// nl6570DeletedOctetOIDs returns the DISTINCT OID names the deletion removed
// from the corpus, in the undotted spelling collectShippedOIDs collects (every
// shipped resource key is undotted; the ledger stores the normalised form).
// Derived from the ledger rather than tabled a second time, so the two views
// cannot drift.
func nl6570DeletedOctetOIDs() []string {
	seen := map[string]struct{}{}
	out := make([]string, 0, len(nl6570DeletedOctetEntries))
	for _, d := range nl6570DeletedOctetEntries {
		o := strings.TrimPrefix(d.oid, ".")
		if _, dup := seen[o]; dup {
			continue
		}
		seen[o] = struct{}{}
		out = append(out, o)
	}
	sort.Strings(out)
	return out
}

// TestOctetShadowRePinIsOnlyTheDeletedOIDs makes the nl6#570 re-pin of
// shippedOIDEncodingDigest self-proving instead of a claim in a comment: put the
// deleted OID names back and the pre-deletion digest must return exactly. It can
// only return if every surviving shipped OID still encodes to the same bytes,
// which is the compatibility claim the re-pin rests on.
func TestOctetShadowRePinIsOnlyTheDeletedOIDs(t *testing.T) {
	deleted := nl6570DeletedOctetOIDs()
	if len(deleted) == 0 {
		t.Fatal("the ledger yielded no OID names")
	}

	// nl6#590 deleted five Cisco names, nl6#588 re-homed aws_s3_storage's
	// sysObjectID value and nl6#576 re-homed the NVIDIA GPU arc, all after this
	// change; undo them newest-first before comparing against a digest taken when
	// none of them had happened.
	oids := nl6576OIDNamesBeforeRehome(nl6588OIDNamesBeforeRehome(
		nl6590OIDNamesBeforeAudit(collectShippedOIDs(t))))
	shipped := map[string]struct{}{}
	for _, o := range oids {
		shipped[o] = struct{}{}
	}
	for _, o := range deleted {
		if _, ok := shipped[o]; ok {
			t.Fatalf("%s is shipped again, so the re-pin's premise is gone: either restore the "+
				"pre-deletion digest or explain the new corpus", o)
		}
	}

	// nl6#574 / nl6#571 / nl6#569 deleted a further 256 OID names after this
	// change, so reaching the pre-octet-shadow digest means undoing both stages.
	// This change's own stage is pinned separately by
	// TestResourceDataDefectRePinIsOnlyTheDeletedOIDs.
	restored := append(append([]string{}, oids...), nl6574RestorableOIDNames(t)...)
	restored = append(restored, deleted...)
	sort.Strings(restored)

	h := sha256.New()
	checked := 0
	for _, oid := range restored {
		if strings.Contains(oid, "{{") {
			continue
		}
		checked++
		// hash.Hash.Write never returns an error, but errcheck cannot know that.
		_, _ = fmt.Fprintf(h, "%s=%x\n", oid, encodeOID(oid))
	}
	got := hex.EncodeToString(h.Sum(nil))

	if got != shippedOIDEncodingDigestBeforeOctetShadowDeletion {
		t.Errorf("restoring %d deleted OID names gives digest %s, want the pre-deletion value %s "+
			"over %d OIDs.\nSo the re-pin of shippedOIDEncodingDigest is NOT explained by this "+
			"deletion alone: something else about what a shipped OID puts on the wire has changed.",
			len(deleted), got, shippedOIDEncodingDigestBeforeOctetShadowDeletion, checked)
	}
	t.Logf("%d OIDs with %d deleted octet-column names restored reproduce the pre-deletion digest",
		checked, len(deleted))
}
