// fixtureLeaf and fixture write the format of
// go/nl6/testdata/gnmi/juniper_mx10004/*-hardware.json. Class is new: it is
// the JSON class the capture proves, since gnmic JSON does not tell uint_val
// from int_val or decimal_val from double_val. Kind is filled from YANG
// later and is not written here.
type fixtureLeaf struct {
	Path   string `json:"path"`
	Kind   string `json:"kind,omitempty"`
	Class  string `json:"class"`
	Always bool   `json:"always,omitempty"`
}

type fixture struct {
	Comment       string        `json:"comment"`
	Subtree       string        `json:"subtree"`
	Prefixes      []string      `json:"prefixes"`
	Notifications int           `json:"notifications"`
	Leaves        []fixtureLeaf `json:"leaves"`
}

// keyRe matches one list key; group 1 is its name, group 2 its value. A
// value may carry an escaped "\]".
var keyRe = regexp.MustCompile(`\[([A-Za-z0-9_.-]+)=((?:\\.|[^\]\\])*)\]`)

// wildKeyRe matches a key reduced to its wildcard.
var wildKeyRe = regexp.MustCompile(`\[[A-Za-z0-9_.-]+=\*\]`)

func wildcardKeys(p string) string { return keyRe.ReplaceAllString(p, "[$1=*]") }

// unreduced reports whether a wildcarded path still holds a bracket outside
// its [k=*] keys: a key value keyRe could not delimit, part of which would
// otherwise reach the fixture.
func unreduced(p string) bool { return strings.ContainsAny(wildKeyRe.ReplaceAllString(p, ""), "[]") }

// splitOrigin cuts gnmic's "origin:path" form. Call it on a wildcarded
// path, so a ':' inside a key value cannot be mistaken for the separator.
// The returned path is absolute.
func splitOrigin(p string) (origin, path string) {
	if i := strings.IndexByte(p, ':'); i >= 0 && !strings.ContainsAny(p[:i], "/[") {
		origin, p = p[:i], p[i+1:]
	}
	return origin, "/" + strings.TrimPrefix(p, "/")
}

// valueClass is the JSON class of one value.
func valueClass(raw json.RawMessage) string {
	v := bytes.TrimSpace(raw)
	if len(v) == 0 {
		return "null"
	}
	switch v[0] {
	case '"':
		return "string"
	case 't', 'f':
		return "bool"
	case 'n':
		return "null"
	case '{', '[':
		return "json"
	}
	if bytes.ContainsAny(v, ".eE") {
		return "fraction"
	}
	return "integer"
}

// mergeClass folds a new observation into a leaf's class. An integer next
// to a fraction is a fraction: a decimal64 or double can print without a
// fractional part. Any other disagreement is an error.
func mergeClass(old, nu string) (string, bool) {
	switch {
	case old == "" || old == nu:
		return nu, true
	case old == "integer" && nu == "fraction", old == "fraction" && nu == "integer":
		return "fraction", true
	}
	return old, false
}

// errUnreduced quotes nothing: the path it refuses is the part that leaked.
var errUnreduced = errors.New("reduce: a path holds a key value the reducer cannot delimit; the path is not shown")

// reduceCapture turns a capture into a value-free fixture. Prefixes and leaf
// paths are wildcarded before anything is stored, so no key value is held
// past the line that read it. A leaf is always if it is in every
// notification of the prefixes it appears under.
func reduceCapture(r io.Reader, subtree, release string) (fixture, error) {
	prefixCount := map[string]int{} // origin:path -> notifications
	leafPrefixes := map[string]map[string]bool{}
	leafSeen := map[string]int{} // notifications carrying the leaf
	leafClass := map[string]string{}
	err := readCapture(r, func(n notification) error {
		wp := wildcardKeys(n.Prefix)
		if unreduced(wp) {
			return errUnreduced
		}
		origin, ppath := splitOrigin(wp)
		pkey := origin + ":" + ppath
		if origin == "" {
			pkey = ppath
		}
		prefixCount[pkey]++
		seen := map[string]bool{}
		for _, u := range n.Updates {
			wu := wildcardKeys(u.Path)
			if unreduced(wu) {
				return errUnreduced
			}
			leaf := strings.TrimSuffix(ppath, "/") + "/" + strings.TrimPrefix(wu, "/")
			for _, raw := range u.Values {
				c, ok := mergeClass(leafClass[leaf], valueClass(raw))
				if !ok {
					return fmt.Errorf("reduce: leaf %s is %s in one notification and %s in another", leaf, leafClass[leaf], valueClass(raw))
				}
				leafClass[leaf] = c
			}
			if !seen[leaf] {
				seen[leaf] = true
				leafSeen[leaf]++
				if leafPrefixes[leaf] == nil {
					leafPrefixes[leaf] = map[string]bool{}
				}
				leafPrefixes[leaf][pkey] = true
			}
		}
		return nil
	})
	if err != nil {
		return fixture{}, err
	}
	fx := fixture{
		Comment: fmt.Sprintf("Shape of a non-public hardware reference (IOS-XR %s) for the %s subscription. "+
			"Values, key values and notification counts are not recorded. class is the JSON class the reference showed; "+
			"kind is filled from YANG. Generated by go/cmd/gnmi-shape reduce.", release, subtree),
		Subtree:  subtree,
		Prefixes: []string{},
		Leaves:   []fixtureLeaf{},
	}
	for p := range prefixCount {
		fx.Prefixes = append(fx.Prefixes, p)
	}
	sort.Strings(fx.Prefixes)
	for leaf, c := range leafClass {
		total := 0
		for p := range leafPrefixes[leaf] {
			total += prefixCount[p]
		}
		fx.Leaves = append(fx.Leaves, fixtureLeaf{Path: leaf, Class: c, Always: leafSeen[leaf] == total})
	}
	sort.Slice(fx.Leaves, func(i, j int) bool { return fx.Leaves[i].Path < fx.Leaves[j].Path })
	return fx, nil
}

func marshalFixture(f fixture) ([]byte, error) {
	b, err := json.MarshalIndent(f, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}
